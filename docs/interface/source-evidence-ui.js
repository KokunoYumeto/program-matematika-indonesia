export function mountEvidenceExplorer() {
  let locale = document.documentElement.lang === 'id' ? 'id' : 'en';
  let index = null, registry = null, selected = null, epoch = 0;
  const el = id => document.getElementById(id), copy = name => evidenceCopy[locale][name] ?? name;
  const node = (tag, text, className) => { const n = document.createElement(tag); if (text != null) n.textContent = text; if (className) n.className = className; return n; };
  const printable = value => value == null ? copy('unknown') : typeof value === 'string' ? value : JSON.stringify(value, null, 2);
  function detail(parent, label, value) {
    if (value == null) return;
    const p = node('div', null, 'field'); p.append(node('h3', copy(label)));
    if (typeof value === 'string') p.append(node('p', value));
    else if (Array.isArray(value) && value.every(x => typeof x === 'string')) {
      const list = node('ul'); for (const item of value) list.append(node('li', item)); p.append(list);
    } else p.append(node('pre', printable(value)));
    parent.append(p);
  }
  function raw(parent, value) { const box = node('details'); box.append(node('summary', copy('raw')), node('pre', JSON.stringify(value, null, 2))); parent.append(box); }
  function action(parent, label, fn) { const button = node('button', label); button.type = 'button'; button.addEventListener('click', fn); parent.append(button); return button; }
  function safeLink(parent, url, label) {
    try { const parsed = new URL(url); if (!['https:', 'http:'].includes(parsed.protocol)) return; const a = node('a', label ?? url); a.href = parsed.href; a.target = '_blank'; a.rel = 'noreferrer noopener'; parent.append(a); } catch { /* an invalid locator stays visible in the inherited record */ }
  }
  function status(parent, record) {
    const state = record?.current_revision_state;
    parent.append(node('p', copy(state ?? 'noObservation'), state === 'changed_requires_reconciliation' ? 'warning' : 'notice'));
  }
  function useCard(use) {
    const card = node('article', null, 'use-card');
    card.append(node('h3', copy(use.role)), node('p', copy('result') + ': ' + use.target.id));
    const work = use.source_work;
    card.append(node('p', copy('author') + ': ' + printable(work.author ?? work.authors)), node('p', copy('work') + ': ' + printable(work.work ?? work.title)));
    detail(card, 'revision', work.source_revision ?? work.version ?? work.revision ?? use.source_identity.revision);
    detail(card, 'fragment', use.native_use);
    detail(card, 'rights', use.reuse_evidence);
    if (use.comparison) detail(card, 'scope', use.comparison);
    safeLink(card, work.source_url ?? work.source_website ?? work.source_repository ?? use.source_identity.source_url);
    action(card, copy('lookupSource'), () => show({type: 'source', id: use.source_binding}));
    action(card, copy('lookupResult') + ' — ' + use.target.id, () => show({type: 'result', kind: use.target.kind, id: use.target.id}));
    action(card, copy('within') + ' — ' + use.within_record.id, () => show({type: 'result', kind: use.within_record.kind, id: use.within_record.id}));
    raw(card, use);
    return card;
  }
  function show(choice, focus = true) {
    selected = choice;
    const panel = el('evidence-detail'); panel.replaceChildren();
    if (!index || !choice) return;
    panel.append(node('h2', choice.id), node('p', copy('originalLanguage'), 'notice'));
    if (choice.type === 'result') {
      const result = index.result(choice.kind, choice.id); if (!result) return;
      const record = result.record;
      status(panel, record ?? result.contexts[0]);
      if (record) {
        detail(panel, 'statement', record.required_statement ?? record.statement);
        detail(panel, 'conditions', record.required_conditions ?? record.conditions);
        detail(panel, 'generality', record.provider_full_generality);
        detail(panel, 'scope', record.provider_scope);
        if (record.proof_locators?.length) { const links = node('div', null, 'links'); links.append(node('h3', copy('proofs'))); for (const p of record.proof_locators) safeLink(links, p.url, p.anchor); panel.append(links); }
      }
      if (result.dependencies.length) detail(panel, 'dependencies', result.dependencies.map(x => x.native_use));
      for (const context of result.contexts) if (context.id !== record?.id) { const box = node('section', null, 'context'); box.append(node('h3', copy('within') + ': ' + context.id)); status(box, context); detail(box, 'conditions', context.required_conditions); detail(box, 'generality', context.provider_full_generality); panel.append(box); }
      panel.append(node('h3', copy('sources')));
      for (const s of result.sources) action(panel, s.binding_id, () => show({type: 'source', id: s.binding_id}));
      panel.append(node('h3', copy('uses')));
      if (!result.uses.length) panel.append(node('p', copy('noUses')));
      for (const use of result.uses) panel.append(useCard(use));
      if (record) raw(panel, record);
    } else {
      const result = index.source(choice.id); if (!result) return;
      const match = registryMatches(result.source, registry);
      panel.append(node('p', copy('registryStatus') + ': ' + copy(match.state)), node('p', copy('registryBoundary'), 'notice'));
      for (const entry of match.records) { const card = node('article'); card.append(node('h3', entry.key + ' — ' + printable(entry.title))); safeLink(card, entry.url); raw(card, entry); panel.append(card); }
      panel.append(node('h3', copy('results')));
      for (const r of result.results) action(panel, r.id, () => show({type: 'result', kind: r.kind, id: r.id}));
      panel.append(node('h3', copy('uses')));
      if (!result.uses.length) panel.append(node('p', copy('noUses')));
      for (const use of result.uses) panel.append(useCard(use));
      raw(panel, result.source);
    }
    if (focus) { panel.focus({preventScroll: true}); panel.scrollIntoView({block: 'start'}); }
  }
  function choices() {
    const query = el('evidence-search').value.toLocaleLowerCase();
    for (const [name, rows, identity, label] of [
      ['result-select', index?.results ?? [], r => JSON.stringify([r.kind, r.id]), r => r.id],
      ['source-select', index?.data.artifact_bindings ?? [], r => r.binding_id, r => {
        const u = index.data.source_uses.find(x => x.source_binding === r.binding_id);
        return (u?.source_work.work ?? u?.source_work.title ?? u?.source_work.author ?? copy('source')) + ' — ' + r.sha256.slice(0, 16);
      }],
    ]) {
      const select = el(name); select.replaceChildren(new Option(copy('choose'), ''));
      let count = 0;
      for (const row of rows) {
        const search = name === 'source-select' ? JSON.stringify(index.source(row.binding_id)) : JSON.stringify(index.result(row.kind, row.id));
        if (query && !search.toLocaleLowerCase().includes(query)) continue;
        select.add(new Option(label(row), identity(row))); count++;
      }
      select.disabled = !count;
      if (!count && index) select.options[0].text = copy('noResults');
    }
  }
  function translate() {
    document.documentElement.lang = locale; document.title = copy('title');
    for (const element of document.querySelectorAll('[data-copy]')) element.textContent = copy(element.dataset.copy);
    el('programme-link').href = '../' + locale + '/programme/';
    el('language').value = locale;
    el('evidence-summary').textContent = index ? [index.results.length + ' ' + copy('resultCount'), index.data.counts.artifact_fingerprints + ' ' + copy('sourceCount'), index.data.counts.source_uses + ' ' + copy('useCount'), index.data.records.filter(r => r.current_revision_state === 'changed_requires_reconciliation').length + ' ' + copy('changedCount')].join(' · ') : copy('empty');
    el('evidence-status').textContent = index ? copy('imported') : copy('empty');
    choices(); show(selected, false);
  }
  async function readSelected(file) { if (file.size > 32 * 1024 * 1024) throw new Error('large'); return file.text(); }
  el('projection-file').addEventListener('change', async event => {
    const file = event.target.files[0]; if (!file) return; const turn = ++epoch;
    // Invalidate old data immediately; a failed replacement must not look current.
    index = null; registry = null; selected = null; el('registry-file').value = ''; translate();
    try { const value = evidenceIndex(JSON.parse(await readSelected(file))); if (turn !== epoch) return; index = value; translate(); }
    catch (error) { if (turn === epoch) el('evidence-status').textContent = copy(error.message === 'large' ? 'large' : 'error'); }
  });
  el('registry-file').addEventListener('change', async event => {
    const file = event.target.files[0]; if (!file) return; const turn = epoch; registry = null;
    try { const value = readRegistry(await readSelected(file)); if (turn !== epoch) return; registry = value; el('evidence-status').textContent = copy('registryLoaded'); show(selected, false); }
    catch (error) { if (turn === epoch) { el('evidence-status').textContent = copy(error.message === 'large' ? 'large' : 'error'); show(selected, false); } }
  });
  el('clear-data').addEventListener('click', () => { epoch++; index = null; registry = null; selected = null; el('projection-file').value = ''; el('registry-file').value = ''; el('evidence-search').value = ''; translate(); });
  el('language').addEventListener('change', event => { locale = event.target.value; translate(); });
  el('evidence-search').addEventListener('input', choices);
  el('result-select').addEventListener('change', event => { if (event.target.value) { const [kind, id] = JSON.parse(event.target.value); show({type: 'result', kind, id}); } });
  el('source-select').addEventListener('change', event => { if (event.target.value) show({type: 'source', id: event.target.value}); });
  translate();
}
