import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { courses } from '../docs/courses.js';

const project = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const overrides = JSON.parse(await readFile(resolve(project, 'backend/authority/learner-tools-overrides-v1.json'), 'utf8'));
const courseIds = new Set(courses.map(({ id }) => id));
const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');
const fileFact = async (relativePath) => {
  const bytes = await readFile(resolve(project, relativePath));
  return { path: relativePath, bytes: bytes.length, sha256: sha256(bytes) };
};

const seenCourses = new Set();
const seenTools = new Set();
const rows = [];
for (const course of overrides.courses) {
  assert.ok(courseIds.has(course.course_id), `Unknown learner-tool course ${course.course_id}.`);
  assert.ok(!seenCourses.has(course.course_id), `Duplicate learner-tool course ${course.course_id}.`);
  seenCourses.add(course.course_id);
  const tools = [];
  for (const input of course.tools) {
    assert.ok(!seenTools.has(input.tool_id), `Duplicate learner tool ${input.tool_id}.`);
    seenTools.add(input.tool_id);
    tools.push({
      tool_id: input.tool_id,
      label: input.label,
      href: input.href,
      action_kind: input.action_kind,
      scope: input.scope,
      state: input.state,
      primary: input.primary,
      machine_data_is_learner_destination: input.machine_data_is_learner_destination,
      page: await fileFact(input.page_path),
      resource: await fileFact(input.resource_path),
      evidence: await fileFact(input.evidence_path),
      limitations: input.limitations,
    });
  }
  rows.push({ course_id: course.course_id, tools });
}

const output = {
  $schema: 'https://kokunoyumeto.github.io/program-matematika-indonesia/schema/v1/learner-tools-v1.schema.json',
  schema_id: 'interlanguage/program-matematika-indonesia/learner-tools/v1',
  schema_version: '1.0.0',
  recorded_at: overrides.recorded_at,
  courses: rows,
};
const bytes = `${JSON.stringify(output, null, 2)}\n`;
const authority = resolve(project, 'backend/authority/learner-tools-v1.json');
const publicJson = resolve(project, 'docs/data/learner-tools-v1.json');
const publicModule = resolve(project, 'docs/learner-tools.js');
await Promise.all([mkdir(dirname(authority), { recursive: true }), mkdir(dirname(publicJson), { recursive: true })]);
await Promise.all([writeFile(authority, bytes, 'utf8'), writeFile(publicJson, bytes, 'utf8')]);
const compactRows = JSON.stringify(rows);
await writeFile(publicModule, `// Generated by scripts/build-learner-tools-v1.mjs. Learner-facing actions point to readable surfaces, never raw machine data.\nexport const learnerToolsRows = Object.freeze(${compactRows});\nexport const learnerToolsByCourseId = Object.freeze(Object.fromEntries(learnerToolsRows.map((row) => [row.course_id, row.tools])));\n`, 'utf8');
assert.deepEqual(await readFile(publicJson), await readFile(authority));
console.log(JSON.stringify({ status: 'PASS', courses: rows.length, tools: seenTools.size, bytes: Buffer.byteLength(bytes), sha256: sha256(Buffer.from(bytes)) }, null, 2));
